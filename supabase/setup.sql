-- Run in the SQL Editor of a NEW Supabase project.
-- The table and column names match the existing app and scraper exactly.
begin;

create table if not exists public."Available Animals" (
    id integer generated by default as identity
        (sequence name public.available_animals_id_seq) primary key,
    created_at timestamptz not null default now(),
    name text not null,
    description text not null default '',
    link text not null unique,
    images jsonb not null default '[]'::jsonb
        check (jsonb_typeof(images) = 'array'),
    tags jsonb not null default '{}'::jsonb
        check (jsonb_typeof(tags) = 'object'),
    "dog/cat" text not null check ("dog/cat" in ('dog', 'cat'))
);

alter table public."Available Animals" enable row level security;

grant usage on schema public to anon, authenticated, service_role;
revoke all on table public."Available Animals" from public, anon, authenticated;
grant select, insert, update, delete on table public."Available Animals" to anon, authenticated;
grant select, insert, update, delete on table public."Available Animals" to service_role;
revoke all on sequence public.available_animals_id_seq from public, anon, authenticated;
grant usage, select on sequence public.available_animals_id_seq to anon, authenticated, service_role;

drop policy if exists "Public can read animals" on public."Available Animals";
create policy "Public can read animals"
    on public."Available Animals" for select
    to anon, authenticated using (true);

-- Preserve the existing shared public-key scraper behavior.
-- These policies allow anyone with that key to modify animal listings.
drop policy if exists "Public can insert animals" on public."Available Animals";
create policy "Public can insert animals"
    on public."Available Animals" for insert
    to anon, authenticated with check (true);

drop policy if exists "Public can update animals" on public."Available Animals";
create policy "Public can update animals"
    on public."Available Animals" for update
    to anon, authenticated using (true) with check (true);

drop policy if exists "Public can delete animals" on public."Available Animals";
create policy "Public can delete animals"
    on public."Available Animals" for delete
    to anon, authenticated using (true);

commit;
